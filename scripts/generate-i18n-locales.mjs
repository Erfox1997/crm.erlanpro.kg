function buildLocale(index) {
  function walk(node) {
    if (Array.isArray(node) && node.length === 2 && typeof node[0] === 'string') {
      return node[index];
    }
    if (node && typeof node === 'object' && !Array.isArray(node)) {
      const out = {};
      for (const [k, v] of Object.entries(node)) {
        if (k === 'useRu') continue;
        out[k] = walk(v);
      }
      return out;
    }
    return node;
  }
  return walk(catalogs);
}

